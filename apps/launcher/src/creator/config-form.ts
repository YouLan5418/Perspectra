export function freeSchema(value: ConfigValue | undefined): ConfigField {
  if (Array.isArray(value)) return { type: 'array', items: {} }
  if (value === null) return { type: 'null' }
  if (typeof value === 'object') return { type: 'object', additionalProperties: {} }
  return { type: typeof value === 'number' ? 'integer' : typeof value === 'boolean' ? 'boolean' : 'string' }
}
export function branchLabel(schema: ConfigField, index: number) {
  if (schema.title) return schema.title
  const tag =
    schema.properties?.kind?.const ??
    schema.properties?.scope?.const ??
    schema.properties?.scope?.enum?.map(v => fieldLabel(String(v))).join(' / ')
  return tag === undefined ? '类型 ' + (index + 1) : fieldLabel(String(tag))
}
export function branchOf(schema: ConfigField, value: ConfigValue | undefined) {
  const obj = configObject(value)
  return Math.max(
    0,
    (schema.oneOf ?? []).findIndex(
      b =>
        (!b.type ||
          (b.type === 'object'
            ? value !== null && typeof value === 'object' && !Array.isArray(value)
            : typeof value === b.type)) &&
        (b.required ?? []).every(k => Object.hasOwn(obj, k)) &&
        Object.entries(b.properties ?? {}).every(
          ([k, s]) =>
            (s.const === undefined || s.const === obj[k]) &&
            (!s.enum || obj[k] === undefined || s.enum.some(v => v === obj[k])),
        ),
    ),
  )
}
export function newField(schema: ConfigField): ConfigValue {
  if (schema.default !== undefined) return JSON.parse(JSON.stringify(schema.default))
  if (schema.type === 'null') return null
  if (schema.const !== undefined) return schema.const
  if (schema.enum?.length) return schema.enum[0]!
  if (schema.oneOf?.length) return newField(schema.oneOf[0]!)
  if (schema.type === 'object')
    return Object.fromEntries((schema.required ?? []).map(key => [key, newField(schema.properties![key]!)]))
  if (schema.type === 'array') return Array.from({ length: schema.minItems ?? 0 }, () => newField(schema.items!))
  if (schema.type === 'boolean') return false
  if (schema.type === 'integer' || schema.type === 'number') return Math.max(0, schema.minimum ?? 0)
  return ''
}
