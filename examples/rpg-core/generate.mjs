import { readFileSync, writeFileSync } from 'node:fs'
import { basename } from 'node:path'
import { pathToFileURL } from 'node:url'
import { activitySource } from './activity.mjs'

// Matches SCRIPT_SOURCE_LIMIT in desktop/host/pack-status.ts. Valid configs stay well below it today
// (about 134 KB at every validation maximum); the check guards future growth of battle-runtime.js.
export const HOST_SOURCE_LIMIT = 256 * 1024

// The output is a normal pack asset: the pack carries it, the asset lock covers it, no host plugin is involved.
export function renderActivityFile(config, from, limit = HOST_SOURCE_LIMIT) {
  const source = `// Generated by examples/rpg-core/generate.mjs from ${from}. Edit that file and regenerate; do not edit by hand.\n${activitySource(config)}\n`
  if (Buffer.byteLength(source, 'utf8') > limit)
    throw new RangeError(`RPG_CONFIG_INVALID: generated activity exceeds the host limit of ${limit} UTF-8 bytes`)
  return source
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [input, output] = process.argv.slice(2)
  if (!input || !output) {
    console.error('Usage: node examples/rpg-core/generate.mjs <battle.config.json> <scripts/activities/<key>.js>')
    process.exit(2)
  }
  writeFileSync(output, renderActivityFile(JSON.parse(readFileSync(input, 'utf8')), basename(input)))
}
