"""Extract executable, MIT-licensed Hindsight search slices without server dependencies."""
import ast
import hashlib
import json
import sys
import textwrap
from pathlib import Path

upstream = Path(sys.argv[1]) / 'hindsight-api-slim/hindsight_api/engine'
target = Path(__file__).resolve().parent / 'vendor/hindsight_api/engine'
manifest = []

def source(name):
    path = upstream / name
    return path.read_text(encoding='utf-8')

def extract(name, identifiers):
    text = source(name)
    nodes = {n.name: n for n in ast.parse(text).body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))}
    pieces = []
    for identifier in identifiers:
        node = nodes[identifier]
        snippet = ast.get_source_segment(text, node)
        pieces.append(snippet)
        manifest.append({'path': name, 'symbol': identifier, 'lines': [node.lineno, node.end_lineno],
                         'sha256': hashlib.sha256(snippet.encode()).hexdigest()})
    return '\n\n'.join(pieces)

header = '# Hindsight MIT source slices; generated by extract_search_slices.py.\nfrom __future__ import annotations\n'
text = source('embeddings.py')
base = next(n for n in ast.parse(text).body if isinstance(n, ast.ClassDef) and n.name == 'Embeddings')
methods = [n for n in base.body if isinstance(n, ast.AsyncFunctionDef) and n.name in
           {'encode_query', 'encode_documents', '_encode_prefixed'}]
base_text = 'class Embeddings:\n' + '\n\n'.join(textwrap.indent(ast.get_source_segment(text, n), '    ') for n in methods)
onnx = header + """import asyncio, logging, os
logger = logging.getLogger(__name__)
DEFAULT_EMBEDDINGS_ONNX_BATCH_SIZE = 32
DEFAULT_EMBEDDINGS_ONNX_CPU_MEM_ARENA = False
DEFAULT_EMBEDDINGS_ONNX_DEVICE = 'cpu'
DEFAULT_EMBEDDINGS_ONNX_CUDA_DEVICE_ID = 0

""" + base_text + '\n\n' + extract('embeddings.py', ['OnnxEmbeddings']) + '\n'
(target / 'onnx_slices.py').write_text(onnx, encoding='utf-8')
for n in methods:
    snippet = ast.get_source_segment(text, n)
    manifest.append({'path': 'embeddings.py', 'symbol': 'Embeddings.' + n.name, 'lines':[n.lineno,n.end_lineno],
                     'sha256':hashlib.sha256(snippet.encode()).hexdigest()})
search = header + """import math, re
from collections.abc import Sequence
from datetime import UTC, datetime
from typing import Any
import numpy as np
from .types import RetrievalResult
EmbeddingLike = Sequence[float]
MAX_TEMPORAL_LINKS_PER_UNIT = 20
_SEMANTIC_WITHIN_BATCH_BLOCK_ROWS = 256
_WHITESPACE_RUN_RE = re.compile(r'\\s+')

""" + extract('retain/link_utils.py', ['_normalize_entity_name', '_cap_links_per_unit',
                                     '_normalize_datetime', '_within_batch_temporal_links', 'compute_semantic_links_within_batch'])
search += '\n\n' + extract('search/retrieval.py', ['_coalesce_date', '_select_with_temporal_coverage'])
graph = source('search/link_expansion_retrieval.py')
start = graph.index('        entity_scores: dict[str, float] = {}')
end = graph.index('        # filter_results_by_tags', start)
block = graph[start:end].rstrip()
search += '\n\ndef merge_expansion_rows(expanded, budget):\n' + textwrap.indent(textwrap.dedent(block), '    ') + '\n    return results\n'
manifest.append({'path':'search/link_expansion_retrieval.py', 'symbol':'LinkExpansionRetriever.retrieve scoring block',
                 'lines':[graph[:start].count('\n')+1,graph[:end].count('\n')],
                 'sha256':hashlib.sha256(block.encode()).hexdigest()})
(target / 'search/portable_slices.py').write_text(search, encoding='utf-8')
(Path(__file__).resolve().parent / 'search-slices.json').write_text(json.dumps(manifest, indent=2),encoding='utf-8')
print(json.dumps({'extractedSymbols':len(manifest)}))
